package io.antarescircuit.antares.hdl.vhdl

import io.antarescircuit.antares.hdl.HDLExportParams
import io.antarescircuit.antares.hdl.HDLModel
import io.antarescircuit.antares.model.DigitalGraph
import io.antarescircuit.antares.model.testcase.Testcase
import io.antarescircuit.jabbah.base.io.CodePrinter
import io.antarescircuit.jabbah.base.logger
import io.antarescircuit.jabbah.base.dsl.DslError
import java.io.FileOutputStream
import java.nio.file.Path

/**
 * Generates the [HDLModel] and exports is as a VHDL circuit file
 * and a VHDL test bench file, if required by [params].
 */
class VHDLGenerator(
	private val params: HDLExportParams,
	private val generateComment: Boolean = false
) {

	companion object {
		private val LOG by logger(VHDLGenerator::class)
		private const val COMMENT = "-- Generated by Antares (www.antarescircuit.io)"
	}

	/**
	 * @throws [DslError] if the [Testcase] used for test bench creation contains an error
	 */
	// Used by the UI
	fun generate(circuit: DigitalGraph) {
		LOG.userTrail("Exporting VHDL for '${circuit.name}' (${circuit.uuid.id})")

		val model = createModel(circuit)
		writeCircuitFile(model, params.hdlFile)
		if (params.testBenchParams != null) {
			writeTestBenchFile(model, params.testBenchParams.tbFile)
		}
	}

	// Used for testing
	fun generateHDL(hdlPrinter: CodePrinter, circuit: DigitalGraph) {
		val model = createModel(circuit)
		writeCircuit(model, hdlPrinter)
	}

	private fun createModel(circuit: DigitalGraph): HDLModel =
		HDLModel(circuit, params.renaming)
			.create()
			.apply { renameLabels() }

	private fun writeCircuit(model: HDLModel, printer: CodePrinter) {
		printComment(printer)
		VHDLCreator(printer, applyDelays = params.useDelayModel).printCircuit(model.main)
		printer.close()
	}

	private fun writeCircuitFile(model: HDLModel, hdlFile: Path) {
		FileOutputStream(hdlFile.toFile()).use {
			CodePrinter(it).also { printer ->
				writeCircuit(model, printer)
			}
		}
	}

	private fun writeTestBench(model: HDLModel, printer: CodePrinter) {
		printComment(printer)
		VHDLTestBenchCreator(printer, model, params.baseName, params.testBenchParams!!).print()
		printer.close()
	}

	private fun writeTestBenchFile(model: HDLModel, tbFile: Path) {
		FileOutputStream(tbFile.toFile()).use {
			CodePrinter(it).also { printer ->
				writeTestBench(model, printer)
			}
		}
	}

	private fun printComment(printer: CodePrinter) {
		if (generateComment) {
			printer.println(COMMENT).println()
		}
	}
}