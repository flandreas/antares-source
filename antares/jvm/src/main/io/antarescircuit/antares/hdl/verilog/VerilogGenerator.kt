package io.antarescircuit.antares.hdl.verilog

import io.antarescircuit.antares.hdl.HDLExportParams
import io.antarescircuit.antares.hdl.HDLModel
import io.antarescircuit.antares.model.DigitalGraph
import io.antarescircuit.antares.model.testcase.Testcase
import io.antarescircuit.jabbah.base.dsl.DslError
import io.antarescircuit.jabbah.base.io.CodePrinter
import io.antarescircuit.jabbah.base.logger
import java.io.FileOutputStream
import java.nio.file.Path

/**
 * Generates the [HDLModel] and exports it as a Verilog circuit file
 * and a Verilog test bench file, if required by [params].
 */
class VerilogGenerator(
	private val params: HDLExportParams,
	private val generateComment: Boolean = false,
) {

	companion object {
		private val LOG by logger(VerilogGenerator::class)
		private const val COMMENT = "// Generated by Antares (www.antarescircuit.io)"
	}

	/**
	 * @throws [DslError] if the [Testcase] used for test bench creation contains an error
	 */
	// Used by the UI
	fun generate(circuit: DigitalGraph) {
		LOG.userTrail("Exporting Verilog for '${circuit.name}' (${circuit.uuid.id})")

		val model = createModel(circuit)
		writeFile(params.hdlFile) { writeCircuit(model, it) }
		if (params.testBenchParams != null) {
			writeFile(params.testBenchParams.tbFile) { writeTestBench(model, it) }
		}
	}

	// Used for testing
	fun generateHDL(hdlPrinter: CodePrinter, circuit: DigitalGraph) {
		writeCircuit(createModel(circuit), hdlPrinter)
	}

	private fun createModel(circuit: DigitalGraph): HDLModel =
		HDLModel(circuit, params.renaming)
			.create()
			.apply { renameLabels() }

	private fun writeCircuit(model: HDLModel, printer: CodePrinter) {
		printHeader(printer)
		VerilogCreator(printer, applyDelays = params.useDelayModel).printCircuit(model.main)
		printer.close()
	}

	private fun writeTestBench(model: HDLModel, printer: CodePrinter) {
		printHeader(printer)
		VerilogTestBenchCreator(printer, model, params.baseName, params.testBenchParams!!).print()
		printer.close()
	}

	private fun writeFile(file: Path, write: (CodePrinter) -> Unit) {
		FileOutputStream(file.toFile()).use {
			write(CodePrinter(it))
		}
	}

	private fun printHeader(printer: CodePrinter) {
		if (generateComment) {
			printer.println(COMMENT).println()
		}
		printer.println(Verilog.TIMESCALE).println()
	}
}
